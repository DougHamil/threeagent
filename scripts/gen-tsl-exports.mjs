// Regenerates src/main/threeagent/tsl/exports.cljc from the installed three/tsl.
// Run after upgrading three: node scripts/gen-tsl-exports.mjs
import * as tsl from 'three/tsl';
import { writeFileSync, readFileSync } from 'node:fs';

const version = JSON.parse(readFileSync(new URL('../node_modules/three/package.json', import.meta.url))).version;
const names = Object.keys(tsl).filter((n) => /^[A-Za-z_$][\w$]*$/.test(n)).sort();

const lines = [];
for (let i = 0; i < names.length; i += 6) {
  lines.push('    ' + names.slice(i, i + 6).map((n) => JSON.stringify(n)).join(' '));
}

writeFileSync(new URL('../src/main/threeagent/tsl/exports.cljc', import.meta.url),
`(ns threeagent.tsl.exports
  "GENERATED by scripts/gen-tsl-exports.mjs from three ${version} - do not edit.
   The names exported by three/tsl, used by the shader compiler to decide
   which symbols refer to TSL.")

(def names
  #{
${lines.join('\n')}})
`);
console.log(`wrote ${names.length} names (three ${version})`);
